import { state, medicineName, findBatch } from "../state.js";
import { $, esc } from "../utils/dom.js";
import { dateTimeText } from "../utils/format.js";
import { pageHeading } from "../components/layout.js";
import { table } from "../components/table.js";
import { movementBadge } from "../components/status.js";

export const title = "Movements";

const HEADERS = ["Type", "Medicine", "Batch", "Quantity", "Timestamp", "Notes"];

function movementTable(list) {
  const rows = list
    .map((m) => {
      const b = findBatch(m.batch_id);
      return `<tr><td>${movementBadge(m.movement_type)}</td><td class="primary-cell">${esc(
        b ? medicineName(b.medicine_id) : "Batch #" + m.batch_id
      )}</td><td>${esc(b?.batch_number || "—")}</td><td class="number-cell">${
        m.quantity
      }</td><td>${dateTimeText(m.timestamp)}</td><td>${esc(m.notes || "—")}</td></tr>`;
    })
    .join("");
  return table(HEADERS, rows, "No stock movements found.");
}

export function render() {
  return (
    pageHeading(
      "AUDIT TRAIL",
      "Stock movements",
      "A chronological record of stock receipts and issues."
    ) +
    `<section class="panel"><div class="toolbar"><span class="toolbar-meta">${
      state.movements.length
    } movements recorded</span><div class="search-box"><span>⌕</span><input id="movementSearch" placeholder="Search medicine, batch or notes…"></div></div>
 <div id="movementTable">${movementTable(
   state.movements
 )}</div><div class="table-foot">Movement records are generated by stock-in, stock-out and initial batch creation.</div></section>`
  );
}

export function bind() {
  const input = $("movementSearch");
  if (!input) return;

  input.addEventListener("input", () => {
    const q = input.value.toLowerCase();
    const list = state.movements.filter((m) => {
      const b = findBatch(m.batch_id);
      return [medicineName(b?.medicine_id), b?.batch_number, m.notes, m.movement_type]
        .join(" ")
        .toLowerCase()
        .includes(q);
    });
    $("movementTable").innerHTML = movementTable(list);
  });
}
